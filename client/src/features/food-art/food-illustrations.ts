// Phrases beat single words; longer terms beat broad matches such as rice or apple.
const matches = (Object.entries(aliases) as [FoodIllustration, string[]][])
  .flatMap(([illustration, terms]) => terms.map((term) => ({ illustration, term })))
  .sort((a, b) => b.term.split(' ').length - a.term.split(' ').length || b.term.length - a.term.length)
  .map(({ illustration, term }) => ({ illustration, pattern: new RegExp(`\\b${term}\\b`) }));

export function matchFoodIllustration(name: string): FoodIllustration | null {
  const normalized = name.toLowerCase().replace(/[^a-z0-9]+/g, ' ');
  return matches.find(({ pattern }) => pattern.test(normalized))?.illustration ?? null;
}
